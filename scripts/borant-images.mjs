export function imageFor(id) {
  if (BORANT_IMAGES[id]) return BORANT_IMAGES[id];
  const prefix = Object.keys(linePhoto).find((p) => id.startsWith(p));
  return prefix ? linePhoto[prefix] : undefined;
}

